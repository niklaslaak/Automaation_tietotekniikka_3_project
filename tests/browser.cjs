const { chromium } = require('playwright');
const assert = require('node:assert/strict');
const path = require('node:path');
const { pathToFileURL } = require('node:url');
(async () => {
  const browser = await chromium.launch({headless:true});
  const page = await browser.newPage({viewport:{width:1280,height:900}});
  const errors = [];
  page.on('pageerror', error => errors.push(error.message));
  await page.goto(pathToFileURL(path.resolve(__dirname, '../index.html')).href);
  assert.equal(await page.locator('#calculate').isDisabled(), true);
  await page.locator('#prices').setInputFiles(path.resolve(__dirname, '../data/esimerkkihinnat.csv'));
  await page.waitForFunction(() => document.querySelector('#file-status').textContent.includes('4 tuntia'));
  await page.locator('#calculate').click();
  assert.match(await page.locator('#cost').textContent(), /0,08/);
  assert.equal(await page.locator('#start').textContent(), '04.11.2026 klo 01:00');
  assert.equal(await page.locator('#end').textContent(), '04.11.2026 klo 03:00');
  assert.equal(await page.locator('#energy').textContent(), '2 kWh');
  await page.locator('#duration').fill('5');
  assert.equal(await page.locator('#result').isVisible(), false);
  await page.locator('#calculate').click();
  assert.match(await page.locator('#error').textContent(), /ylittää aineiston/);
  await page.locator('#duration').fill('2');
  await page.locator('#calculate').click();
  await page.locator('#prices').setInputFiles(path.resolve(__dirname, '../data/virhe-puuttuva-tunti.csv'));
  await page.waitForFunction(() => document.querySelector('#error').textContent.includes('peräkkäisiä'));
  assert.equal(await page.locator('#result').isVisible(), false);
  assert.equal(await page.locator('#calculate').isDisabled(), true);
  await page.locator('#prices').setInputFiles(path.resolve(__dirname, '../data/negatiiviset-hinnat.csv'));
  await page.waitForFunction(() => !document.querySelector('#calculate').disabled);
  await page.locator('#calculate').click();
  assert.match(await page.locator('#cost').textContent(), /0,02/);
  assert.ok((await page.locator('#cost').textContent()).includes('−') || (await page.locator('#cost').textContent()).includes('-'));
  await page.locator('#power').fill('1,5');
  assert.equal(await page.locator('#result').isVisible(), false);
  await page.locator('#calculate').click();
  assert.match(await page.locator('#cost').textContent(), /0,03/);
  await page.setViewportSize({width:375,height:812});
  assert.equal(await page.evaluate(() => document.documentElement.scrollWidth <= innerWidth), true);
  await page.reload();
  assert.equal(await page.locator('#calculate').isDisabled(), true);
  assert.equal(await page.locator('#result').isVisible(), false);
  assert.deepEqual(errors, []);
  console.log(`PASS: Chromium ${browser.version()}; local file launch, CSV upload, normal result, changed inputs, excessive duration, invalid import, negative prices, decimal comma, mobile width, reload, no page errors.`);
  await browser.close();
})().catch(error => {console.error(error);process.exit(1);});
